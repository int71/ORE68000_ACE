	//	・垂直帰線コマンド(VBCommand)
	//		ラインバッファ処理が不要となる垂直帰線期間でのみ実行可能な、VRAM操作コマンドです。
	//		ラインバッファ程の高度な合成処理は行えませんが、
	//		16MHz動作「MC68000」によるVRAM操作より高速かつ、並行動作が可能です。
	//		ただしコマンド実行中に垂直帰線期間が終了すると、コマンド実行は中断されます。
	//		「VI71B」は下記を根拠に「2MHz動作」であり、VRAM操作性能はここから定まります。
	//
	//			最大出力:1024(ドット)*512(ドット)*60(フレーム/秒)
	//			演算性能:16(ドット/クロック)
	//			VRAMアクセス性能:16(WORD/クロック)
	//
	//		フレームレート60Hz、表示走査線480本、垂直帰線45本である場合、
	//		1走査線当たり「trunc(2,000,000*16/(525*60))=1,015(WORD)※小数点以下切り捨て」、
	//		1フレーム当たりだと「1,015*45=45,675(WORD)」のVRAM操作を行えます。
	//		ただし、VRAM操作は読み取り、書き込みで独立して各々「1アクセス」扱いとなるため、
	//		「コピー」コマンドは1走査線当たり「507(WORD)」と性能半減します。
	//		一方「テキスト」VRAM領域での「複数プレーン書き込み」は有効であるため、
	//		320ドットx240ドット「テキスト」のクリアなら「20x240=4,800(WORD)」の書き込みで済み、
	//		垂直帰線5本分の時間で完了できます。
	//		VRAM操作は「矩形」単位で行うため、処理範囲は1次元の「長さ」でなく、
	//		2次元の「縦横幅」および「ピッチ(縦方向の折り返しサイズ)」で指定します。
	//		「ピッチ」はVRAM用途とは無関係に任意の「2の累乗」値を指定でき、
	//		その範囲は「1～32,768(WORD)」となります。
